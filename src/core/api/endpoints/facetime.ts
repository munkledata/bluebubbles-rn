import { z } from 'zod/v4';
import { ApiError } from '../errors';
import type { HttpClient } from '../http';

// 16 hex characters today (generateTempGuid); 8 for an attempt made before review M090.
const TEMP_GUID = /^temp-[a-z0-9]{8,64}$/;
const E164_FACETIME_CALL_ADDRESS = /^\+[1-9][0-9]{1,14}$/u;
const LOWERCASE_ASCII_EMAIL_LOCAL_PART =
  /^[a-z0-9!#$%&'*+/=?^_`{|}~-]+(?:\.[a-z0-9!#$%&'*+/=?^_`{|}~-]+)*$/u;
const ASCII_EMAIL_DOMAIN_LABEL = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/u;

// 16 bytes encode as 22 unpadded base64url characters. Canonical encoding leaves four zero bits,
// so the final alphabet character can only be A/Q/g/w. The 32-byte key similarly has two zero
// bits and therefore one of the 16 final characters below. These constraints reject alternate
// spellings that decode to the same bearer values.
const CANONICAL_FACETIME_LINK =
  /^https:\/\/facetime\.apple\.com\/join#v=1&p=[A-Za-z0-9_-]{21}[AQgw]&k=[A-Za-z0-9_-]{42}[AEIMQUYcgkosw048]$/u;

export interface CreateFaceTimeLinkParams {
  /** Fresh, single-attempt idempotency identity generated by the client. */
  readonly tempGuid: string;
}

export interface FaceTimeLinkAck {
  readonly link: string;
}

export interface StartFaceTimeCallParams {
  /** Exact canonical recipient submitted by the user; this boundary never rewrites it. */
  readonly address: string;
  /** `true` starts video; `false` starts audio. */
  readonly video: boolean;
  /** Fresh, single-attempt idempotency identity generated by the client. */
  readonly tempGuid: string;
}

export interface FaceTimeCallStartAck {
  readonly started: true;
}

/** Exact Apple FaceTime bearer-link shape accepted from the server. */
export function isCanonicalAppleFaceTimeLink(value: unknown): value is string {
  return typeof value === 'string' && CANONICAL_FACETIME_LINK.test(value);
}

/** Exact narrow call target: canonical E.164 or an already-lowercase ASCII email address. */
export function isCanonicalFaceTimeCallAddress(value: unknown): value is string {
  if (typeof value !== 'string' || value.length === 0 || value.length > 254) return false;
  if (E164_FACETIME_CALL_ADDRESS.test(value)) return true;
  if (value !== value.toLowerCase() || !/^[\x21-\x7e]+$/u.test(value)) return false;

  const separator = value.indexOf('@');
  if (separator <= 0 || separator !== value.lastIndexOf('@')) return false;
  const localPart = value.slice(0, separator);
  const domain = value.slice(separator + 1);
  if (localPart.length > 64 || !LOWERCASE_ASCII_EMAIL_LOCAL_PART.test(localPart)) return false;

  const labels = domain.split('.');
  return labels.length >= 2 && labels.every((label) => ASCII_EMAIL_DOMAIN_LABEL.test(label));
}

function outcomeUnknown(status?: number): ApiError {
  // Never attach the response, Zod issues, or received URL: the link is a bearer credential and
  // must not reach generic error serialization or diagnostics.
  return new ApiError(
    'parse_error',
    'FaceTime link creation outcome could not be confirmed',
    status,
    undefined,
    undefined,
    'facetime_link_outcome_unknown',
  );
}

function isExactFaceTimeLinkAck(value: unknown): value is FaceTimeLinkAck {
  if (typeof value !== 'object' || value == null || Array.isArray(value)) return false;
  const record = value as Record<string, unknown>;
  return Object.keys(record).length === 1 && isCanonicalAppleFaceTimeLink(record.link);
}

function callOutcomeUnknown(status?: number): ApiError {
  return new ApiError(
    'parse_error',
    'FaceTime call start outcome could not be confirmed',
    status,
    undefined,
    undefined,
    'facetime_call_start_outcome_unknown',
  );
}

function isExactFaceTimeCallStartAck(value: unknown): value is FaceTimeCallStartAck {
  return hasExactTrueMarker(value, 'started');
}

function hasExactTrueMarker(value: unknown, marker: string): boolean {
  if (typeof value !== 'object' || value == null || Array.isArray(value)) return false;
  try {
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return false;
    const keys = Reflect.ownKeys(value);
    if (keys.length !== 1 || keys[0] !== marker) return false;
    const descriptor = Object.getOwnPropertyDescriptor(value, marker);
    return descriptor?.enumerable === true && 'value' in descriptor && descriptor.value === true;
  } catch {
    return false;
  }
}

/** POST one plain FaceTime link request, once, and accept only an exact canonical acknowledgement. */
export async function createFaceTimeLink(
  http: HttpClient,
  params: CreateFaceTimeLinkParams,
): Promise<FaceTimeLinkAck> {
  if (!TEMP_GUID.test(params.tempGuid)) {
    throw new Error('FaceTime link creation needs a fresh client-generated temporary GUID.');
  }

  let raw: unknown;
  try {
    // Keep the transport schema intentionally opaque, then perform the exact check below. A schema
    // issue can retain its rejected input; for this endpoint that input could be the bearer URL.
    raw = await http.post('/facetime/link', z.unknown(), {
      captureErrorDetail: true,
      retry: false,
      json: { tempGuid: params.tempGuid },
    });
  } catch (error) {
    if (error instanceof ApiError && error.kind !== 'parse_error') throw error;
    if (error instanceof ApiError || error instanceof z.ZodError) {
      throw outcomeUnknown(error instanceof ApiError ? error.status : undefined);
    }
    throw error;
  }

  if (!isExactFaceTimeLinkAck(raw)) throw outcomeUnknown();
  return { link: raw.link };
}

/** POST one exact FaceTime call request, once, and accept only the reserved success marker. */
export async function startFaceTimeCall(
  http: HttpClient,
  params: StartFaceTimeCallParams,
): Promise<FaceTimeCallStartAck> {
  if (!isCanonicalFaceTimeCallAddress(params.address)) {
    throw new Error('A FaceTime call needs a canonical E.164 number or lowercase ASCII email.');
  }
  if (typeof params.video !== 'boolean') {
    throw new Error('A FaceTime call needs an exact audio/video choice.');
  }
  if (!TEMP_GUID.test(params.tempGuid)) {
    throw new Error('A FaceTime call needs a fresh client-generated temporary GUID.');
  }

  let raw: unknown;
  try {
    raw = await http.post('/facetime/call', z.unknown(), {
      captureErrorDetail: true,
      retry: false,
      json: {
        address: params.address,
        video: params.video,
        tempGuid: params.tempGuid,
      },
    });
  } catch (error) {
    if (error instanceof ApiError && error.kind !== 'parse_error') throw error;
    if (error instanceof ApiError || error instanceof z.ZodError) {
      throw callOutcomeUnknown(error instanceof ApiError ? error.status : undefined);
    }
    throw error;
  }

  if (!isExactFaceTimeCallStartAck(raw)) throw callOutcomeUnknown();
  return { started: true };
}
